export function createDecoderFixture(): QrFrame {
  const width = (size + 8) * 4;
  const pixels = new Uint8ClampedArray(width * width * 4);
  for (let y = 0; y < width; y++) {
    for (let x = 0; x < width; x++) {
      const mx = Math.floor(x / 4) - 4;
      const my = Math.floor(y / 4) - 4;
      const dark =
        mx >= 0 && my >= 0 && mx < size && my < size && pattern[my * size + mx];
      const offset = (y * width + x) * 4;
      pixels[offset] = pixels[offset + 1] = pixels[offset + 2] = dark ? 0 : 255;
      pixels[offset + 3] = 255;
    }
  }
  return { pixels, width, height: width };
}
